"""Generates app/src/main/java/helium314/keyboard/clackatoo/OmarchyThemeData.kt from the colour tables of Omarchy.

Omarchy (https://github.com/basecamp/omarchy, MIT, Copyright (c) David Heinemeier Hansson) keeps one
`themes/<name>/colors.toml` per colour theme. This script reads exactly those files at the pinned commit below and
copies the twelve colour roles that every theme defines. It never touches wallpapers, images or any other file of
the repository. The mapping of the roles to keyboard colours (and the contrast check) is Kotlin: OmarchyThemes.kt.

    python3 tools/omarchy-themes/generate.py            # fetch from GitHub at the pinned commit (needs network)
    python3 tools/omarchy-themes/generate.py --source ~/src/omarchy   # a local clone, checked out at the pinned commit
    python3 tools/omarchy-themes/generate.py --check    # fail if the checked-in file differs from a fresh generation

Needs Python 3.11 or later (tomllib); standard library only.
"""
import argparse
import hashlib
import subprocess
import sys
import tomllib
import urllib.request
from pathlib import Path

COMMIT = "600ca886632d4e0e2bba5afb759b3bb8d382cddc"
THEMES = [
    "catppuccin-latte", "catppuccin", "ethereal", "everforest", "flexoki-light", "gruvbox", "hackerman", "jade-horse",
    "kanagawa", "last-horizon", "lumon", "lupine", "matte-black", "miasma", "nord", "retro-82", "ristretto", "rose-pine",
    "solitude", "starship", "tokyo-night", "vantablack", "white",
]
# the roles that all 23 themes define, in the order of OmarchyColors' constructor
ROLES = [
    "accent", "selection", "muted", "background", "dark_background", "darker_background", "lighter_background",
    "foreground", "dark_foreground", "light_foreground", "bright_foreground",
]
RAW = "https://raw.githubusercontent.com/basecamp/omarchy/%s/%s"
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app/src/main/java/helium314/keyboard/clackatoo/OmarchyThemeData.kt"


def fetch(path: str, source: Path | None) -> bytes:
    if source is not None:
        return (source / path).read_bytes()
    with urllib.request.urlopen(RAW % (COMMIT, path), timeout=60) as response:
        return response.read()


def display_name(slug: str) -> str:
    special = {"catppuccin-latte": "Catppuccin Latte", "retro-82": "Retro 82", "rose-pine": "Rosé Pine"}
    return special.get(slug) or slug.replace("-", " ").title()


def color_literal(value: str) -> str:
    value = value.strip().lstrip("#")
    if len(value) != 6 or any(c not in "0123456789abcdefABCDEF" for c in value):
        raise ValueError("not a #rrggbb colour: %r" % value)
    return "0xFF%s.toInt()" % value.upper()


def generate(source: Path | None) -> str:
    license_text = fetch("LICENSE", source)
    repo_license = (ROOT / "third_party/omarchy/LICENSE").read_bytes()
    if license_text != repo_license:
        sys.exit("third_party/omarchy/LICENSE differs from the licence at the pinned commit")
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// GENERATED by tools/omarchy-themes/generate.py, do not edit. Colours only.",
        "//",
        "// Colour roles of the Omarchy themes (https://github.com/basecamp/omarchy, MIT, Copyright (c) David Heinemeier",
        "// Hansson; licence in third_party/omarchy/LICENSE), copied from themes/<name>/colors.toml at commit",
        "// %s." % COMMIT,
        "// No wallpaper or other image of Omarchy is used. sha256 is the checksum of each colors.toml.",
        "package helium314.keyboard.clackatoo",
        "",
        "internal const val OMARCHY_COMMIT = \"%s\"" % COMMIT,
        "",
        "internal val OMARCHY_THEME_DATA: List<OmarchyColors> = listOf(",
    ]
    for slug in THEMES:
        raw = fetch("themes/%s/colors.toml" % slug, source)
        table = tomllib.loads(raw.decode("utf-8"))
        mode = table.get("mode")
        if mode not in ("dark", "light"):
            sys.exit("%s: mode must be dark or light, got %r" % (slug, mode))
        missing = [r for r in ROLES if r not in table]
        if missing:
            sys.exit("%s: missing roles %s" % (slug, missing))
        lines.append("    OmarchyColors(")
        lines.append('        id = "%s", name = "%s", dark = %s,' % (slug, display_name(slug), "true" if mode == "dark" else "false"))
        lines.append('        sha256 = "%s",' % hashlib.sha256(raw).hexdigest())
        for role in ROLES:
            camel = "".join(w.capitalize() if i else w for i, w in enumerate(role.split("_")))
            lines.append("        %s = %s," % (camel, color_literal(table[role])))
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=Path, help="local clone of basecamp/omarchy checked out at the pinned commit")
    parser.add_argument("--check", action="store_true", help="compare with the checked-in file instead of writing it")
    args = parser.parse_args()
    if args.source is not None:
        head = subprocess.run(["git", "-C", str(args.source), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
        if head != COMMIT:
            sys.exit("--source is at %s, not at the pinned commit %s" % (head or "?", COMMIT))
    text = generate(args.source)
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit("%s is out of date; run generate.py" % OUT.relative_to(ROOT))
        print("up to date: %d themes at %s" % (len(THEMES), COMMIT[:10]))
    else:
        OUT.write_text(text, encoding="utf-8")
        print("wrote %s (%d themes at %s)" % (OUT.relative_to(ROOT), len(THEMES), COMMIT[:10]))


if __name__ == "__main__":
    main()
